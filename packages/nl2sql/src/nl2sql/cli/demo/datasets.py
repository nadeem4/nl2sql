"""The three databases the demo project ships, gathered into one place.

``chinook`` is vendored; ``support`` and ``webanalytics`` are generated by
``scripts/generate_demo_datasets.py`` and share Chinook's customer identities,
so the demo shows several datasources rather than one. The resolver's
single-datasource shortcut no longer applies with three registered, which is
the point: the vector search and the answerability judge run for real.
"""

from .chinook import (
    CHINOOK_DATASOURCE,
    CHINOOK_QUESTIONS,
    CHINOOK_TABLES_BY_ROLE,
)
from .support import (
    SUPPORT_DATASOURCE,
    SUPPORT_QUESTIONS,
    SUPPORT_TABLES_BY_ROLE,
)
from .webanalytics import (
    WEBANALYTICS_DATASOURCE,
    WEBANALYTICS_QUESTIONS,
    WEBANALYTICS_TABLES_BY_ROLE,
)

# (datasource id, packaged file name, datasource config). The file name is both
# what is copied out of ``nl2sql.datasets`` and what the connection points at
# under the demo project's ``data/``.
DEMO_DATABASES = (
    ("chinook", "chinook.sqlite", CHINOOK_DATASOURCE),
    ("support", "support.sqlite", SUPPORT_DATASOURCE),
    ("webanalytics", "webanalytics.sqlite", WEBANALYTICS_DATASOURCE),
)

DEMO_DATASOURCES = [config for _, _, config in DEMO_DATABASES]

# Example questions per datasource. Indexing embeds these into each
# datasource's vector chunk, which is how the resolver tells the three apart.
DEMO_QUESTIONS_BY_DATASOURCE = {
    "chinook": list(CHINOOK_QUESTIONS),
    "support": list(SUPPORT_QUESTIONS),
    "webanalytics": list(WEBANALYTICS_QUESTIONS),
}

# The guided questions the playground offers, and the list ``--record`` walks.
# Chinook's twelve come first so the demo opens on familiar ground. There are
# no cross-database questions here: the engine plans each sub-query against a
# single datasource, so a question spanning two cannot be answered yet.
DEMO_QUESTIONS = [
    *CHINOOK_QUESTIONS,
    *SUPPORT_QUESTIONS,
    *WEBANALYTICS_QUESTIONS,
]

_TABLES_BY_ROLE = {
    "chinook": CHINOOK_TABLES_BY_ROLE,
    "support": SUPPORT_TABLES_BY_ROLE,
    "webanalytics": WEBANALYTICS_TABLES_BY_ROLE,
}


def _qualified(role: str) -> list[str]:
    """Every ``datasource.table`` a role may read, across the three databases."""
    return [
        f"{ds_id}.{table}"
        for ds_id, by_role in _TABLES_BY_ROLE.items()
        for table in by_role[role]
    ]


def _datasources_for(role: str) -> list[str]:
    """The datasources a role may reach, dropping any it has no table in."""
    return [ds_id for ds_id, by_role in _TABLES_BY_ROLE.items() if by_role[role]]


# The demo's RBAC, one policy per role across all three datasources. Admin sees
# everything; the analyst reads no employee or agent table; the viewer reads no
# customer, invoice or ticket-message data, which leaves it the music catalog
# and the non-identifying half of web analytics, and no support access at all.
DEMO_POLICIES = {
    "admin": {
        "description": "Every table in every demo database",
        "role": "admin",
        "allowed_datasources": ["*"],
        "allowed_tables": ["*"],
    },
    "analyst": {
        "description": "Everything except employee and support-agent records",
        "role": "analyst",
        "allowed_datasources": _datasources_for("analyst"),
        "allowed_tables": _qualified("analyst"),
    },
    "viewer": {
        "description": "Music catalog and anonymous web traffic; no customers, sales or support",
        "role": "viewer",
        "allowed_datasources": _datasources_for("viewer"),
        "allowed_tables": _qualified("viewer"),
    },
}

