"""The three databases the demo project ships, gathered into one place.

``chinook`` is vendored; ``support`` and ``webanalytics`` are generated by
``scripts/generate_demo_datasets.py`` and share Chinook's customer identities,
so the demo shows several datasources rather than one. The resolver's
single-datasource shortcut no longer applies with three registered, which is
the point: the vector search and the answerability judge run for real.

The dicts are in the shape of ``nl2sql.yaml``. ``nl2sql.config.demo_config``
builds the demo ``Config`` from them, and ``nl2sql init --demo`` writes that
config out as files.
"""

from .chinook import (
    CHINOOK_DATASOURCE,
    CHINOOK_QUESTIONS,
    CHINOOK_ROLES,
    CHINOOK_VERIFIED_QUERIES,
)
from .support import (
    SUPPORT_DATASOURCE,
    SUPPORT_QUESTIONS,
    SUPPORT_ROLES,
)
from .webanalytics import (
    WEBANALYTICS_DATASOURCE,
    WEBANALYTICS_QUESTIONS,
    WEBANALYTICS_ROLES,
)

# (datasource id, packaged file name, datasource config). The file name is both
# what is copied out of ``nl2sql.datasets`` and the connection's ``database``.
DEMO_DATABASES = (
    ("chinook", "chinook.sqlite", CHINOOK_DATASOURCE),
    ("support", "support.sqlite", SUPPORT_DATASOURCE),
    ("webanalytics", "webanalytics.sqlite", WEBANALYTICS_DATASOURCE),
)

DEMO_DATASOURCES = [config for _, _, config in DEMO_DATABASES]

# Example questions per datasource. Indexing embeds these into each
# datasource's vector chunk, which is how the resolver tells the three apart.
DEMO_QUESTIONS_BY_DATASOURCE = {
    "chinook": list(CHINOOK_QUESTIONS),
    "support": list(SUPPORT_QUESTIONS),
    "webanalytics": list(WEBANALYTICS_QUESTIONS),
}

# The demo's ``curated`` section: verified queries by datasource. Only Chinook
# has them.
DEMO_CURATED = {
    "datasources": {"chinook": {"verified_queries": CHINOOK_VERIFIED_QUERIES}},
}

# The guided questions the playground offers, and the list ``--record`` walks.
# Chinook's twelve come first so the demo opens on familiar ground. There are
# no cross-database questions here: the engine plans each sub-query against a
# single datasource, so a question spanning two cannot be answered yet.
DEMO_QUESTIONS = [
    *CHINOOK_QUESTIONS,
    *SUPPORT_QUESTIONS,
    *WEBANALYTICS_QUESTIONS,
]

_ROLES = (CHINOOK_ROLES, SUPPORT_ROLES, WEBANALYTICS_ROLES)


def _patterns(role: str, description: str) -> dict:
    """One role's allow and deny patterns, merged across the three databases."""
    allow = [p for roles in _ROLES for p in roles[role].get("allow", [])]
    deny = [p for roles in _ROLES for p in roles[role].get("deny", [])]
    return {"description": description, "allow": allow, **({"deny": deny} if deny else {})}


# The demo's policies, one role across all three datasources. Admin sees
# everything; the analyst reads every database but the employee and agent
# tables, which it denies; the viewer is an allow list with no customer,
# invoice or ticket-message data, which leaves it the music catalog and the
# non-identifying half of web analytics, and no support access at all.
DEMO_POLICIES = {
    "admin": {"description": "Every table in every demo database", "allow": ["*"]},
    "analyst": _patterns("analyst", "Everything except employee and support-agent records"),
    "viewer": _patterns("viewer", "Music catalog and anonymous web traffic; no customers, sales or support"),
}

